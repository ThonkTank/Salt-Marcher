import {TerrainSpatialView} from '../src/app/terrain-spatial-view';
import {atlasPreviewScene} from './atlas-preview-scene';
import {heightRecord} from '../src/app/terrain-height';
import {emptyRecord,type LandscapeRecord} from '../src/app/atlas-landscape';
import {newLine} from '../src/app/landscape-line';
import {routeSpec} from '../src/app/terrain-route';
import {planRoute} from '../src/app/terrain-route-planner';
import {spatialTerrainSurface} from '../src/app/spatial-terrain';
const base=[-1,0].flatMap(y=>[-1,0].map(x=>heightRecord(x*512,y*512,8,Float32Array.from({length:4096},(_,i)=>{
  const xx=x*512+i%64*8,yy=y*512+Math.floor(i/64)*8;
  return 80-xx*.03+65*Math.exp(-((xx+25)**2+(yy-80)**2)/4500);
}))));
const line=(kind:'road'|'river',name:string,points:{x:number;y:number}[],width:number):LandscapeRecord=>({...emptyRecord(kind),id:name,name,points,width,line:{...newLine(kind),roughness:0,meander:0},route:routeSpec(kind,points)});
const road=line('road','Hangstraße',[{x:-240,y:-20},{x:-20,y:-20},{x:240,y:20}],10);
const river=line('river','Talfluss',[{x:-240,y:-140},{x:0,y:-110},{x:230,y:-130}],16);
const tunnel=line('road','Tunnel',[{x:-240,y:80},{x:240,y:80}],10);tunnel.route!.sections=['tunnel'];
const bridge=line('road','Brücke',[{x:-240,y:200},{x:240,y:200}],10);bridge.route!.sections=['bridge'];
const ford=line('road','Furt',[{x:-240,y:-240},{x:240,y:-240}],8);ford.route!.sections=['ford'];
for(const [id,y,level,width] of [['bridge-water',200,90,60],['ford-water',-240,80.4,20]] as const)base.push({...emptyRecord('patch'),id,surface:'freshwater',waterLevelM:level,polygons:[{outer:[{x:-width/2,y:y-22},{x:width/2,y:y-22},{x:width/2,y:y+22},{x:-width/2,y:y+22}],holes:[]}]});
const requests=[road,river,tunnel,bridge,ford];
const plans=requests.map(r=>planRoute(base,r));
const box={x:-320,y:-300,width:640,height:620};
const views=[...document.querySelectorAll<HTMLCanvasElement>('canvas')].map(c=>new TerrainSpatialView(c));
const scene=(records:LandscapeRecord[])=>({revision:1,box,records,instances:[],buildings:[],...spatialTerrainSurface([...base,...records],box,.8)});
views[0]!.setData(atlasPreviewScene(scene(requests.map(r=>{const copy=structuredClone(r);delete copy.route;return copy;}))));
views[1]!.setData(atlasPreviewScene(scene(plans)));
for(const view of views)view.reframe(box,45,0);
for(const id of ['top','tilt'])document.getElementById(id)!.onclick=()=>{for(const view of views){view.reframe(box,id==='top'?0:45,0);}};
new ResizeObserver(()=>views.forEach(v=>v.render())).observe(document.body);
document.body.dataset.ready='true';
Object.assign(window,{routeProbe:{read:()=>plans.map(r=>({name:r.name,nodes:r.route!.nodes.length,structures:[...new Set(r.route!.nodes.map(n=>n.structure))]}))}});
